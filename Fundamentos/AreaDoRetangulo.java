/*
Cálculo da Área de um Retângulo

Criar um programa Java que calcule a área
de um retângulo com base em sua largura e altura.
*/

public class AreaDoRetangulo{
	public static void main(String[] args) {
		double largura = 5.0D;
		double altura = 3.0D;
		double area = largura * altura;
		System.out.println("O retângulo de:");
		System.out.println("Largura = " + largura);
		System.out.println("E altura = " + altura);
		System.out.println("Possui área = " + area);
	}
}